import { jsPDF } from 'jspdf';
import type { ExamPaper } from '../types';
import { translations } from '../translations';

export function downloadExamPaperPdf(paperId: string) {
  // Use English dictionary copy for PDF generation so standard jsPDF fonts render every mathematical character cleanly without missing glyph boxes.
  const paper: ExamPaper | undefined = translations.en.examPapers.find((p) => p.id === paperId);
  if (!paper) return;

  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 16;
  const maxWidth = pageWidth - margin * 2;
  let y = 18;

  const ensureSpace = (needed: number) => {
    if (y + needed > 276) {
      doc.addPage();
      y = 18;
    }
  };

  const addWrapped = (text: string, fontSize: number, style: 'normal' | 'bold', color: [number, number, number], indent = 0) => {
    doc.setFont('helvetica', style);
    doc.setFontSize(fontSize);
    doc.setTextColor(color[0], color[1], color[2]);
    const lines = doc.splitTextToSize(text, maxWidth - indent) as string[];
    const lineHeight = fontSize * 0.45;
    for (const line of lines) {
      ensureSpace(lineHeight + 2);
      doc.text(line, margin + indent, y);
      y += lineHeight;
    }
  };

  // Header
  addWrapped('KINGDOM OF CAMBODIA - MINISTRY OF EDUCATION, YOUTH AND SPORT (MoEYS)', 9, 'bold', [18, 54, 107]);
  y += 1.5;
  addWrapped(paper.title, 15, 'bold', [18, 54, 107]);
  y += 1;
  addWrapped(
    `Source: MoEYS Open Exam Archive  |  Verified Answer Key  |  Weight: ${paper.points} pts  |  Duration: ${paper.durationMinutes} min`,
    9,
    'normal',
    [100, 116, 139]
  );
  y += 3;
  doc.setDrawColor(18, 54, 107);
  doc.setLineWidth(0.5);
  doc.line(margin, y, pageWidth - margin, y);
  y += 7;

  // Part I: Examination Paper
  addWrapped('PART I — EXAMINATION QUESTIONS', 11, 'bold', [244, 119, 0]);
  y += 3;

  for (const ex of paper.exercises) {
    ensureSpace(20);
    addWrapped(`${ex.number} (${ex.points} pts) — ${ex.topic}`, 11, 'bold', [30, 41, 59]);
    y += 1;
    addWrapped(ex.statement, 10, 'normal', [30, 41, 59], 2);
    y += 1;
    for (const part of ex.subParts) {
      addWrapped(part, 10, 'normal', [51, 65, 85], 5);
      y += 0.5;
    }
    y += 4;
  }

  // Part II: Verified Answer Key
  ensureSpace(22);
  doc.setDrawColor(203, 213, 225);
  doc.setLineWidth(0.3);
  doc.line(margin, y, pageWidth - margin, y);
  y += 7;
  addWrapped('PART II — VERIFIED STEP-BY-STEP OFFICIAL SOLUTIONS', 11, 'bold', [18, 54, 107]);
  y += 3;

  for (const ex of paper.exercises) {
    ensureSpace(22);
    addWrapped(`${ex.number}: ${ex.topic}`, 10.5, 'bold', [18, 54, 107]);
    y += 1;
    for (const step of ex.solutionSteps) {
      addWrapped(step, 9.5, 'normal', [30, 41, 59], 4);
      y += 0.5;
    }
    addWrapped(`Final Answer: ${ex.finalAnswer}`, 9.5, 'bold', [5, 150, 105], 4);
    y += 0.5;
    addWrapped(`Grading Checkpoint: ${ex.gradingNote}`, 9, 'normal', [180, 83, 9], 4);
    y += 4;
  }

  addWrapped('Generated by EduBridge Cambodia — Learn Smarter. Prepare Better. Discover Your Future.', 8.5, 'normal', [100, 116, 139]);
  doc.save(`${paper.id}-edubridge-verified.pdf`);
}
